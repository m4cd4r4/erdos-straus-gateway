def all_qr_analysis(prime_limit=500_000):
    """
    For p = 1,2,4 (mod 7) Case B primes: t=1 requires (p+7)/4 to have
    a QNR prime factor mod 7. If not, t=1 fails entirely.
    Study: what determines x_dist for these 'all-QR at t=1' primes?
    """
    print(f"\n{'='*60}")
    print(f"ALL-QR ANALYSIS (p=1,2,4 mod 7 Case B, primes to {prime_limit:,})")
    print(f"{'='*60}")

    qr7 = {1, 2, 4}
    primes = sieve_primes(prime_limit)
    case_b_qr7 = [p for p in primes if is_case_b(p) and p % 7 in qr7]
    print(f"  p = QR (1,2,4) mod 7, Case B: {len(case_b_qr7):,}")

    # Classify: t=1 works or not?
    t1_works = []
    t1_fails = []

    for p in case_b_qr7:
        x_lo = (p + 3) // 4
        x1 = x_lo + 1
        B1_factors = prime_factors_set(p * x1)
        # t=1 works if B1 has a QNR factor mod 7
        has_qnr = any(f % 7 in {3, 5, 6} for f in B1_factors if f != 7)
        if has_qnr:
            t1_works.append(p)
        else:
            t1_fails.append(p)

    print(f"  t=1 works (B1 has QNR mod 7): {len(t1_works):,} ({100*len(t1_works)/max(len(case_b_qr7),1):.1f}%)")
    print(f"  t=1 fails (B1 all-QR mod 7):  {len(t1_fails):,} ({100*len(t1_fails)/max(len(case_b_qr7),1):.1f}%)")

    # For t1_fails: what is x_dist?
    t0 = time.time()
    t_dist = defaultdict(int)
    hardest = []
    for p in t1_fails:
        t_sol, _, _, _, _ = find_solution_t(p)
        if t_sol:
            t_dist[t_sol] += 1
            if t_sol >= 7:
                hardest.append((t_sol, p))

    elapsed = time.time() - t0
    print(f"\n  X-dist for t=1-fails ({len(t1_fails)} primes, {elapsed:.1f}s):")
    for t in sorted(t_dist.keys()):
        A = 3 + 4 * t
        print(f"    t={t:2d} (A={A}): {t_dist[t]:5,}")

    print(f"\n  Hardest primes in t=1-fail group (t>=7):")
    hardest.sort(reverse=True)
    for t_sol, p in hardest[:10]:
        x_lo = (p + 3) // 4
        x1 = x_lo + 1
        B1_facs = prime_factors_set(p * x1)
        qnr_facs = {f for f in B1_facs if f % 7 in {3,5,6}}
        print(f"    p={p:9d} (p mod 7={p%7}): x_dist={t_sol}, "
              f"B1 QNR-mod7 factors={sorted(qnr_facs)[:3]}")

    # Now among t1_fails: classify by t=2 success
    if t1_fails[:100]:
        print(f"\n  For t=1-fail primes: B2 mod 11 analysis (A2=11):")
        nqr11 = {q for q in range(1, 11) if legendre_symbol(q, 11) == -1}
        print(f"  QNRs mod 11: {sorted(nqr11)}")
        by_b2nqr = defaultdict(int)
        for p in t1_fails[:500]:
            x_lo = (p + 3) // 4
            x2 = x_lo + 2
            B2_factors = prime_factors_set(p * x2)
            has_qnr11 = any(f % 11 in nqr11 for f in B2_factors if f != 11)
            by_b2nqr[has_qnr11] += 1
        print(f"  t=2 criterion (B2 has QNR mod 11): "
              f"works={by_b2nqr[True]}, fails={by_b2nqr[False]} (of first 500)")


