    print(f"{'='*60}")

    # Known hardest: p=806521 (x_dist=19)
    hard_primes = [806521, 1915201, 1282009]

    for p in hard_primes:
        print(f"\n  p = {p} (mod 24={p%24}, mod 7={p%7}):")
        x_lo = (p + 3) // 4
        print(f"    x_lo = {x_lo}")

        # Trace t=1..20: for each prime A_t, does B_t have QNR factor?
        print(f"    t-scan (prime A_t only):")
        found_t = None
        for t in range(1, 25):
            x = x_lo + t
            A = 3 + 4 * t
            B = p * x
            # Check if A is prime
            is_prime_A = all(A % d != 0 for d in range(2, min(A, int(A**0.5)+1)))
            if not is_prime_A:
                continue
            B_factors = prime_factors_set(B)
            qnr_factors = {f for f in B_factors if f != A and legendre_symbol(f % A, A) == -1}
            b_mod_A = B % A
            neg_b_mod_A = (A - b_mod_A) % A
            subgrp = subgroup_mod_p(B_factors - {A}, A)
            can_solve = neg_b_mod_A in subgrp
            status = "SOLVE" if can_solve else "FAIL "
            # Find actual solution
            y_min = (B + A - 1) // A
            sol_found = False
            for y in range(y_min, y_min + 100):
                d = A * y - B
                if d > 0 and (B * y) % d == 0:
                    sol_found = True
                    if found_t is None:
                        found_t = t
                    break
            sol_str = "sol!" if sol_found else "    "
            print(f"      t={t:2d} A={A:3d}: B mod A={b_mod_A:3d}, -B mod A={neg_b_mod_A:3d}, "
                  f"QNR-facs={sorted(qnr_factors)[:2]}, {status} {sol_str}")
            if sol_found and found_t == t:
                print(f"      => FIRST SOLUTION at t={t}!")
                break


