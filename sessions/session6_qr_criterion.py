def verify_qr_criterion(prime_limit=300_000):
    """
    For each Case B prime, verify:
    - At x_dist t: B_t has a QNR prime factor mod A_t (A_t prime).
    - At x_dist t-1: If A_{t-1} is prime, B_{t-1} has NO QNR factor mod A_{t-1}.
    Show the criterion explains the x_dist distribution.
    """
    print(f"\n{'='*60}")
    print(f"QR CRITERION VERIFICATION (Case B primes to {prime_limit:,})")
    print(f"{'='*60}")

    # Primes A_t = 3+4t that are themselves prime (good for QR analysis)
    prime_A_t = {t: 3 + 4*t for t in range(1, 30) if
                 all((3+4*t) % d != 0 for d in range(2, int((3+4*t)**0.5)+1))
                 or (3+4*t) < 4}
    # Fix: include t where 3+4t is prime
    prime_A_t = {}
    for t in range(1, 30):
        A = 3 + 4*t
        if A >= 2 and all(A % d != 0 for d in range(2, int(A**0.5)+1)):
            prime_A_t[t] = A
    print(f"\n  t values where A_t = 3+4t is prime: {prime_A_t}")

    primes = sieve_primes(prime_limit)
    case_b = [p for p in primes if is_case_b(p)]
    print(f"  Case B primes: {len(case_b):,}")

    criterion_confirmed = 0
    criterion_mismatch = 0
    t_breakdown = defaultdict(lambda: {'qnr_ok': 0, 'qnr_fail': 0, 'composite_A': 0})

    t0 = time.time()
    for p in case_b:
        x_lo = (p + 3) // 4
        t_sol, _, _, _, _ = find_solution_t(p)
        if t_sol is None:
            continue

        x = x_lo + t_sol
        A = 3 + 4 * t_sol
        B = p * x
        B_factors = prime_factors_set(B)

        if t_sol in prime_A_t:
            # Check: does B_t have a QNR factor mod A?
            has_qnr = any(legendre_symbol(f, A) == -1 for f in B_factors if f != A)
            if has_qnr:
                t_breakdown[t_sol]['qnr_ok'] += 1
                criterion_confirmed += 1
            else:
                t_breakdown[t_sol]['qnr_fail'] += 1
                criterion_mismatch += 1
        else:
            t_breakdown[t_sol]['composite_A'] += 1

    elapsed = time.time() - t0
    print(f"\n  QR Criterion check ({elapsed:.1f}s):")
    print(f"  Confirmed (B_t has QNR factor when A_t prime): {criterion_confirmed}")
    print(f"  Mismatch (no QNR factor found, A_t prime): {criterion_mismatch}")
    print(f"\n  Breakdown by t:")
    for t in sorted(t_breakdown.keys()):
        b = t_breakdown[t]
        A = 3 + 4 * t
        is_prime = t in prime_A_t
        print(f"    t={t:2d} (A={A:3d}, {'PRIME' if is_prime else 'composite'}): "
              f"qnr_ok={b['qnr_ok']}, qnr_fail={b['qnr_fail']}, comp_A={b['composite_A']}")


