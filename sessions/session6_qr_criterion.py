def pmod7_analysis(prime_limit=500_000):
    """
    Key insight: B_1 = p*(p+7)/4 = 2p^2 (mod 7), always a QR mod 7.
    -B_1 mod 7 is always a NQR. t=1 works iff B_1 has a QNR prime factor mod 7.
    B_1 has p as a factor. p is QNR mod 7 iff p = 3,5,6 (mod 7).
    => p = 3,5,6 (mod 7): t=1 always works (for Case B primes).
    => p = 1,2,4 (mod 7): need (p+7)/4 to have QNR factor mod 7.

    This analysis: confirm this prediction against empirical x_dist data.
    """
    print(f"\n{'='*60}")
    print(f"p MOD 7 STRUCTURE (Case B, primes to {prime_limit:,})")
    print(f"{'='*60}")

    qr7 = {1, 2, 4}   # QRs mod 7 (1^2=1,2^2=4,3^2=2 -> {1,2,4})
    nqr7 = {3, 5, 6}

    primes = sieve_primes(prime_limit)
    case_b = [p for p in primes if is_case_b(p)]

    by_pmod7 = defaultdict(lambda: defaultdict(int))
    t0 = time.time()
    for p in case_b:
        pm7 = p % 7
        t_sol, _, _, _, _ = find_solution_t(p)
        if t_sol is None:
            continue
        by_pmod7[pm7][t_sol] += 1

    elapsed = time.time() - t0
    print(f"\n  Case B primes: {len(case_b):,} in {elapsed:.1f}s")
    print(f"\n  QRs mod 7: {sorted(qr7)} (p = these mod 7 => p is QR, t=1 harder)")
    print(f"  NQRs mod 7: {sorted(nqr7)} (p = these mod 7 => p is QNR, t=1 works)")

    print(f"\n  X-dist by p mod 7:")
    for pm7 in sorted(by_pmod7.keys()):
        dist = by_pmod7[pm7]
        total = sum(dist.values())
        t1_pct = 100 * dist.get(1, 0) / total if total else 0
        max_t = max(dist.keys()) if dist else 0
        qr_str = "QR " if pm7 in qr7 else "NQR"
        print(f"    p = {pm7} (mod 7) [{qr_str}]: n={total:5,}, "
              f"x_dist=1: {t1_pct:5.1f}%, max_t={max_t}")

    # The key prediction: p = NQR (3,5,6 mod 7) => x_dist ALWAYS = 1
    print(f"\n  PREDICTION: p = NQR (3,5,6 mod 7) => x_dist always 1.")
    for pm7 in sorted(nqr7):
        dist = by_pmod7[pm7]
        total = sum(dist.values())
        non_t1 = {t: c for t, c in dist.items() if t != 1}
        if non_t1:
            print(f"    p = {pm7} (mod 7): {total} primes. NON-t1 cases: {non_t1}")
        else:
            print(f"    p = {pm7} (mod 7): {total} primes. ALL x_dist=1. ?")


