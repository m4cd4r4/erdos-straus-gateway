def sieve_primes(limit):
    is_prime = bytearray([1]) * (limit + 1)
    is_prime[0] = is_prime[1] = 0
    for i in range(2, int(limit**0.5) + 1):
        if is_prime[i]:
            is_prime[i*i::i] = bytearray(len(is_prime[i*i::i]))
    return [i for i in range(2, limit + 1) if is_prime[i]]


def prime_factors_set(n):
    """Return set of distinct prime factors of n."""
    factors = set()
    d = 2
    while d * d <= n:
        if n % d == 0:
            factors.add(d)
            while n % d == 0:
                n //= d
        d += 1
    if n > 1:
        factors.add(n)
    return factors


def legendre_symbol(a, p):
    """Legendre symbol (a/p) for prime p. Returns 0, 1, or -1."""
    if a % p == 0:
        return 0
    ls = pow(a, (p - 1) // 2, p)
    return -1 if ls == p - 1 else ls


def is_qr_mod_p(a, p):
    """True if a is a quadratic residue (or 0) mod prime p."""
    return legendre_symbol(a % p, p) >= 0


def subgroup_mod_p(factors, p):
    """
    Compute the multiplicative subgroup of (Z/pZ)* generated by
    {f mod p : f in factors, f not divisible by p}.
    Returns the set of residues reachable as products of prime factors.
    """
    generators = {f % p for f in factors if f % p != 0}
    reachable = {1}
    for g in generators:
        new_reachable = set()
        for r in reachable:
            cur = 1
            for _ in range(p - 1):  # group order divides p-1
                cur = (cur * g) % p
                new_reachable.add((r * cur) % p)
                if cur == 1:
                    break
        reachable |= new_reachable
        # Also include g and its powers directly
        cur = g
        for _ in range(p - 1):
            reachable.add(cur)
            cur = (cur * g) % p
            if cur == 1:
                break
    return reachable


def is_case_b(p):
    """True if p=1(mod 24) and x_lo=(p+3)/4 has all prime factors =1(mod 3)."""
    if p % 24 != 1:
        return False
    x_lo = (p + 3) // 4
    n = x_lo
    d = 2
    while d * d <= n:
        if n % d == 0:
            if d % 3 == 2:
                return False
            while n % d == 0:
                n //= d
        d += 1
    return not (n > 1 and n % 3 == 2)


def find_solution_t(p, max_t=50):
    """Find minimum t where 4/p = 1/(x_lo+t) + 1/y + 1/z has a solution."""
    x_lo = (p + 3) // 4
    for t in range(1, max_t + 1):
        x = x_lo + t
        A = 4 * x - p
        B = p * x
        y_min = (B + A - 1) // A
        for y in range(y_min, y_min + 20000):
            d = A * y - B
            if d > 0 and (B * y) % d == 0:
                z = (B * y) // d
                if z > 0:
                    return t, x, y, z, d
    return None, None, None, None, None


